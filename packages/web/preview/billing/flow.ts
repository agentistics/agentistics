// Dev-only: drives the real Billing page (preview ?view=final) through a plan change and checks the write.
import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const fail: string[] = []
await page.goto('http://127.0.0.1:5391/?view=final&n=3&theme=dark')
await page.waitForTimeout(1200)
await page.locator('[data-billing-row="acc_c2"] button:not([role="switch"])').first().click()
await page.waitForTimeout(400)
await page.getByText('Claude Max 5x', { exact: true }).last().click()
await page.waitForTimeout(200)
await page.getByText('Claude Pro', { exact: true }).last().click()
await page.waitForTimeout(300)
if (!(await page.getByText(/Troca de plano/).count())) fail.push('no plan-change note')
await page.getByRole('button', { name: 'Salvar' }).click()
await page.waitForTimeout(500)
const saved = await page.evaluate(() => (window as unknown as { __saved: { accountProfiles: Record<string, { periods: { planId: string; from: string; to?: string }[] }> } }).__saved)
const ps = saved?.accountProfiles?.acc_c2?.periods ?? []
const today = new Date().toISOString().slice(0, 10)
const yday = new Date(Date.now() - 864e5).toISOString().slice(0, 10)
const max = ps.find(p => p.planId === 'anthropic-max-5x')
const pro = ps.filter(p => p.planId === 'anthropic-pro' && p.from === today && !p.to)
if (max?.to !== yday) fail.push(`old plan not closed yesterday: ${JSON.stringify(max)}`)
if (pro.length !== 1) fail.push(`new plan not open from today: ${JSON.stringify(ps)}`)
if (await page.locator('[role="dialog"]').count()) fail.push('drawer still open')
const rowText = await page.locator('[data-billing-row="acc_c2"]').innerText()
if (!rowText.includes('Claude Pro')) fail.push(`row does not show the new plan: ${rowText}`)
// The codex row: "Não sei agora" stores an unknown period (N/A, never 0)
await page.locator('[data-billing-row="acc_x1"] button:not([role="switch"])').first().click()
await page.waitForTimeout(300)
await page.getByRole('button', { name: 'Não sei agora' }).click()
await page.waitForTimeout(400)
const s2 = await page.evaluate(() => (window as unknown as { __saved: { accountProfiles: Record<string, { periods: { mode: string }[] }> } }).__saved)
if (s2?.accountProfiles?.acc_x1?.periods?.[0]?.mode !== 'unknown') fail.push('not sure did not store unknown')
await browser.close()
console.log(fail.length ? `FAIL\n${fail.join('\n')}` : 'flow ok')
